export function translateUiText(value: string, language: AppLanguage): string {
  if (language === 'en') return value;
  const direct = vietnameseUiCopy[value] ?? vietnameseRuntimeCopy[value] ?? vietnameseCanonicalValueCopy[value];
  if (direct) return direct;
  const phrase = value.match(/^(\d[\d,.]*)% coverage$/);
  if (phrase) return `${phrase[1]}% độ bao phủ`;
  const scored = value.match(/^([\d,.]+) scored$/);
  if (scored) return `${scored[1]} đã chấm điểm`;
  const targets = value.match(/^(\d+) targets$/);
  if (targets) return `${targets[1]} target`;
  const alerts = value.match(/^(\d[\d,.]*) alerts$/);
  if (alerts) return `${alerts[1]} cảnh báo`;
  const matchPercent = value.match(/^([\d,.]+)% match$/);
  if (matchPercent) return `${matchPercent[1]}% khớp`;
  const scoredStatus = value.match(/^(Anomaly|Normal) \(([^)]+)\)$/);
  if (scoredStatus) return `${translateUiText(scoredStatus[1], language)} (${scoredStatus[2]})`;
  const ppPair = value.match(/^([\d,.]+) pp \/ ([\d,.]+) pp vs last 7 days$/);
  if (ppPair) return `${ppPair[1]} điểm % / ${ppPair[2]} điểm % so với 7 ngày trước`;
  const pp = value.match(/^([\d,.]+) pp vs last 7 days$/);
  if (pp) return `${pp[1]} điểm % so với 7 ngày trước`;
  const vsLastSeven = value.match(/^([\d,.]+) vs last 7 days$/);
  if (vsLastSeven) return `${vsLastSeven[1]} so với 7 ngày trước`;
  return value;
}

export function useUiText() {
  const language = useAppLanguage();
  return (value: string) => translateUiText(value, language);
}

